import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../src/ui/', import.meta.url);
const result = await Bun.build({
	entrypoints: [fileURLToPath(new URL('browser/dashboard.ts', root)), fileURLToPath(new URL('dashboard.css', root))],
	target: 'browser',
	format: 'iife',
	minify: true,
});
if (!result.success) throw new AggregateError(result.logs, 'Dashboard build failed');
const javascript = result.outputs.find(output => output.path.endsWith('.js'));
const css = result.outputs.find(output => output.path.endsWith('.css'));
if (!javascript || !css) throw new Error('Dashboard build did not produce JavaScript and CSS');
// Both assets are embedded into nonce-protected HTML raw-text elements.
const script = (await javascript.text()).replace(/<\/script/gi, '<\\/script');
const style = (await css.text()).replace(/<\/style/gi, '<\\/style');
await mkdir(new URL('dist/', root), { recursive: true });
await Bun.write(
	new URL('dist/assets.ts', root),
	[
		'// Generated by bun run build:ui. Edit src/ui sources instead.',
		`export const script = ${JSON.stringify(script)};`,
		`export const style = ${JSON.stringify(style)};`,
		'',
	].join('\n'),
);
